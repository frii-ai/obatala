func TestRunValidationRetry(t *testing.T) {
	var bad map[string]any
	if err := json.Unmarshal([]byte(goodDraft), &bad); err != nil {
		t.Fatal(err)
	}
	bad["id"] = "Not Kebab Case"
	badJSON, err := json.Marshal(bad)
	if err != nil {
		t.Fatal(err)
	}
	llmFake := &fakeLLM{replies: []string{string(badJSON), goodDraft}}
	deps, opts := baseOptions(t.TempDir(), llmFake)

	if _, err := creator.Run(context.Background(), deps, opts); err != nil {
		t.Fatalf("run: %v", err)
	}
	if llmFake.calls != 2 {
		t.Fatalf("llm calls = %d, want 2", llmFake.calls)
	}
}

func TestRunDuplicateIDRetry(t *testing.T) {
	suite := t.TempDir()
	// Pre-existing scenario with the id the LLM first proposes.
	seed := `id: lowball-final-budget
name: Pre-existing
customer:
  description: x
  strategy: y
  max_turns: 1
criteria:
  success:
    - The bot greets the customer
budgets:
  max_turns: 2
  turn_latency_p95_ms: 30000
`
	if err := os.WriteFile(filepath.Join(suite, "existing.yaml"), []byte(seed), 0o644); err != nil {
		t.Fatal(err)
	}
	var dup map[string]any
	if err := json.Unmarshal([]byte(goodDraft), &dup); err != nil {
		t.Fatal(err)
	}
	dup["id"] = "lowball-final-budget-v2"
	dupJSON, _ := json.Marshal(dup)

	// First reply collides with the pre-existing id; retry returns v2.
	llmFake := &fakeLLM{replies: []string{goodDraft, string(dupJSON)}}
	deps, opts := baseOptions(suite, llmFake)

	result, err := creator.Run(context.Background(), deps, opts)
	if err != nil {
		t.Fatalf("run: %v", err)
	}
	if llmFake.calls != 2 {
		t.Fatalf("llm calls = %d, want 2", llmFake.calls)
	}
	if result.ID != "lowball-final-budget-v2" {
		t.Fatalf("id = %q", result.ID)
	}
}

