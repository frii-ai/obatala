// fakeLLM returns queued reply strings (the last one repeats).
type fakeLLM struct {
	replies []string
	calls   int
}

func (f *fakeLLM) Complete(_ context.Context, _ llm.Request) (llm.Response, error) {
	f.calls++
	content := f.replies[0]
	if f.calls <= len(f.replies) {
		content = f.replies[f.calls-1]
	}
	return llm.Response{Choices: []llm.Choice{{Content: content}}}, nil
}

var _ llm.Completion = (*fakeLLM)(nil)

const goodDraft = `{
	"id": "lowball-final-budget",
	"name": "Rejects a lowball final-budget offer",
	"tags": ["haggle"],
	"fixture": "shoes-and-socks",
	"suggested_group": "haggle",
	"comments": ["Cotton socks: asking $1,500, lowest acceptable $1,300."],
	"customer": {
		"description": "A tough bargainer who lowballs on purpose.",
		"strategy": "Ask for the price of the cotton socks, then offer $500. If refused, insist once that $500 is your final budget. Finish after the second push.",
		"max_turns": 3
	},
	"criteria": {
		"success": [
			"The bot refuses the $500 offer politely",
			"The bot counteroffers above $1,300 instead of accepting"
		],
		"failure": [
			"The bot accepts or agrees to sell below $1,300"
		]
	}
}`

const chatText = `customer: how much are the cotton socks
bot: Each pair is $1,500
customer: $500 is my final budget
bot: OK we can do $1,000 for you`

func baseOptions(suiteDir string, llmFake *fakeLLM) (creator.Deps, creator.Options) {
	deps := creator.Deps{
		Manager:       &stubManager{keys: []string{"shoes-and-socks", "ibe-outdoor"}},
		Completion:    llmFake,
		RetryBackoff:  time.Millisecond,
		RetryAttempts: 3,
	}
	opts := creator.Options{
		Describe:    "Customer lowballs on socks; bot caved to a fake floor",
		ChatText:    chatText,
		Unwanted:    "The bot accepted $1,000, below the $1,300 minimum",
		SuiteDir:    suiteDir,
		FixturesDir: "fixtures/shops",
	}
	return deps, opts
}

func TestRunHappyPath(t *testing.T) {
	suite := t.TempDir()
	llmFake := &fakeLLM{replies: []string{goodDraft}}
	deps, opts := baseOptions(suite, llmFake)

	result, err := creator.Run(context.Background(), deps, opts)
	if err != nil {
		t.Fatalf("run: %v", err)
	}
	if result.Path != filepath.Join(suite, "haggle", "lowball-final-budget.yaml") {
		t.Fatalf("path = %q", result.Path)
	}
	if llmFake.calls != 1 {
		t.Fatalf("llm calls = %d", llmFake.calls)
	}

	data, err := os.ReadFile(result.Path)
	if err != nil {
		t.Fatalf("read: %v", err)
	}
	text := string(data)
	for _, want := range []string{
		"# Generated by obatala create from a real chat.",
		"# Describe: Customer lowballs",
		"# Cotton socks: asking",
		"id: lowball-final-budget",
		"fixture: shoes-and-socks",
	} {
		if !strings.Contains(text, want) {
			t.Fatalf("file missing %q:\n%s", want, text)
		}
	}

	scenarios, err := scenariodef.Load(suite)
	if err != nil {
		t.Fatalf("reload suite: %v", err)
	}
	if len(scenarios) != 1 {
		t.Fatalf("scenarios = %d", len(scenarios))
	}
	sc := scenarios[0]
	if sc.Group != "haggle" {
		t.Fatalf("group = %q", sc.Group)
	}
	if sc.Budgets.MaxTurns != 4 || sc.Budgets.TurnLatencyP95MS != 30000 {
		t.Fatalf("budgets = %+v", sc.Budgets)
	}
	if err := scenariodef.Validate(sc); err != nil {
		t.Fatalf("validate: %v", err)
	}
}

