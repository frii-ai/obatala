func TestRunRefusesExistingWithoutForce(t *testing.T) {
	suite := t.TempDir()
	out := filepath.Join(t.TempDir(), "target.yaml")
	if err := os.WriteFile(out, []byte("# hand-tuned scenario\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	llmFake := &fakeLLM{replies: []string{goodDraft}}
	deps, opts := baseOptions(suite, llmFake)
	opts.OutPath = out

	if _, err := creator.Run(context.Background(), deps, opts); err == nil || !strings.Contains(err.Error(), "-force") {
		t.Fatalf("run err = %v, want exists/-force error", err)
	}

	opts.Force = true
	result, err := creator.Run(context.Background(), deps, opts)
	if err != nil {
		t.Fatalf("force run: %v", err)
	}
	if !strings.Contains(string(result.YAML), "id: lowball-final-budget") {
		t.Fatalf("yaml:\n%s", result.YAML)
	}
	data, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(data), "Generated by obatala create") {
		t.Fatalf("file not overwritten:\n%s", data)
	}
}

func TestRunDryRunWritesNothing(t *testing.T) {
	suite := t.TempDir()
	llmFake := &fakeLLM{replies: []string{goodDraft}}
	deps, opts := baseOptions(suite, llmFake)
	opts.DryRun = true
	var stdout bytes.Buffer
	opts.Stdout = &stdout

	result, err := creator.Run(context.Background(), deps, opts)
	if err != nil {
		t.Fatalf("run: %v", err)
	}
	if result.Path != "" {
		t.Fatalf("path = %q, want empty", result.Path)
	}
	if !strings.Contains(stdout.String(), "id: lowball-final-budget") {
		t.Fatalf("stdout:\n%s", stdout.String())
	}
	entries, err := os.ReadDir(suite)
	if err != nil {
		t.Fatal(err)
	}
	if len(entries) != 0 {
		t.Fatalf("suite not empty: %v", entries)
	}
}

